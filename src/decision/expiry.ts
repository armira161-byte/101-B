// РЕФАКТОРИНГ (бинарные опционы, Фаза 0): подтверждённый баг — карточка
// сигнала показывала recommendedExpiry (адаптивная оценка 1-4 бара по
// волатильности/режиму), а реальный резолв ВЕЗДЕ был захардкожен на "ровно
// 1 бар после сигнала" (outcome-scheduler.ts::resolveOutcome брал
// candlesAfterSignal[0], useDemoAccountStore.ts::openTrade считал expiryAt
// как ровно одну свечу выбранного таймфрейма) — то есть отображаемое и
// реальное время экспирации могли не совпадать.
//
// Продуктовое решение (Фаза 0, п.1, вариант "а" — рекомендованный):
// фиксированная экспирация по таймфрейму, как на классических платформах
// бинарных опционов — пользователь выбирает длительность контракта самим
// выбором таймфрейма (M1/M3/M5 и т.д.), а сама сделка всегда резолвится
// ровно через EXPIRY_BARS баров ЭТОГО таймфрейма после сигнала. Один бар —
// самая честная и предсказуемая интерпретация "экспирация = длительность
// свечи": никакой скрытой адаптивной логики, которую пользователь не видит
// и не может учесть в риск-менеджменте.
//
// EXPIRY_BARS — единственное место, которое нужно поменять, чтобы
// синхронно изменить резолв everywhere (см. expiry-consistency.test.ts).
export const EXPIRY_BARS = 1;
